const assert = require('node:assert/strict');
const {validateState, estimateRow, summarize} = require('./dashboard-core.js');
const row = {id:'honeygain',included:true,status:'testing',basis:'measured',days:7,earnedUsd:7,scenarioUsd:null,costInr:100,actualCostInr:50,feeUsd:2.02,loss:3,balanceUsd:3,minimumUsd:20,cashInr:0};
const state = {version:1,fx:85,target:30000,month:'2026-11',rows:[row]};
assert.equal(validateState(state).rows.length,1);
assert.ok(Math.abs(estimateRow(row,85).net - 2206.951) < 1e-6);
assert.equal(estimateRow(row,85).thresholdDays,17);
assert.equal(estimateRow({...row,earnedUsd:null},85).net,null);
assert.equal(estimateRow({...row,earnedUsd:0},85).net,-100);
assert.equal(estimateRow({...row,basis:'scenario',earnedUsd:7,scenarioUsd:50},85).grossUsd,50);
assert.equal(estimateRow({...row,earnedUsd:0},85).thresholdDays,null);
assert.equal(estimateRow({...row,balanceUsd:20},85).thresholdDays,0);
assert.equal(estimateRow({...row,minimumUsd:null},85).thresholdDays,null);
assert.throws(()=>validateState({...state,rows:[row,row]}),/Duplicate/);
assert.throws(()=>validateState({...state,rows:[{...row,days:0}]}),/days/);
assert.throws(()=>validateState({...state,rows:[{...row,cashInr:-1}]}),/cashInr/);
assert.throws(()=>validateState({...state,fx:0}),/fx/);
assert.throws(()=>validateState({...state,month:'2026-99'}),/month/);
assert.throws(()=>validateState({...state,rows:[{...row,id:'<script>'}]}),/id/);
assert.throws(()=>validateState({...state,rows:[{...row,status:'installed-and-paid'}]}),/status/);
assert.throws(()=>validateState({...state,password:'secret'}),/Unexpected/);
const catalog = [{id:'honeygain',mode:'passive'},{id:'testing-work',mode:'active'}];
const totals = summarize({...state,rows:[row,{...row,id:'testing-work',earnedUsd:70,cashInr:1000}]},catalog);
assert.ok(totals.active > totals.passive);
assert.equal(totals.cash,1000);
assert.equal(totals.actualCosts,100);
assert.equal(totals.netCash,900);
assert.equal(summarize({...state,rows:[{...row,status:'paused'}]},catalog).passive,0);
assert.equal(summarize({...state,rows:[{...row,included:false}]},catalog).passive,0);
assert.equal(summarize({...state,rows:[{...row,basis:'scenario',scenarioUsd:50}]},catalog).passive,0);
assert.ok(summarize({...state,rows:[{...row,basis:'scenario',scenarioUsd:50}]},catalog).scenarioPassive>0);
console.log('PASS: observation estimates, missing/zero income, threshold timing, scenario separation, pooled rows and strict import validation.');
