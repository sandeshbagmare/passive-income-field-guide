const assert = require('node:assert/strict');
const {validateState, estimateRow, summarize, workloadForGap} = require('./dashboard-core.js');
const row = {id:'honeygain',included:true,status:'testing',basis:'measured',payoutKind:'cash',days:7,earnedUsd:7,scenarioUsd:null,costInr:100,actualCostInr:50,feeUsd:2.02,loss:3,balanceUsd:3,minimumUsd:20,cashInr:0};
const state = {version:3,fx:85,target:30000,month:'2026-11',activeHourlyNetInr:null,weeklyHoursAvailable:null,rows:[row]};
assert.equal(validateState(state).rows.length,1);
assert.equal(validateState(state).version,3);
assert.ok(Math.abs(estimateRow(row,85).net - 2206.951) < 1e-6);
assert.equal(estimateRow(row,85).thresholdDays,17);
assert.equal(estimateRow({...row,earnedUsd:null},85).net,null);
assert.equal(estimateRow({...row,earnedUsd:0},85).net,-100);
assert.equal(estimateRow({...row,basis:'scenario',earnedUsd:7,scenarioUsd:50},85).grossUsd,50);
assert.equal(estimateRow({...row,earnedUsd:0},85).thresholdDays,null);
assert.equal(estimateRow({...row,balanceUsd:20},85).thresholdDays,0);
assert.equal(estimateRow({...row,minimumUsd:null},85).thresholdDays,null);
assert.throws(()=>validateState({...state,rows:[row,row]}),/Duplicate/);
assert.throws(()=>validateState({...state,rows:[{...row,days:0}]}),/days/);
assert.throws(()=>validateState({...state,rows:[{...row,cashInr:-1}]}),/cashInr/);
assert.throws(()=>validateState({...state,fx:0}),/fx/);
assert.throws(()=>validateState({...state,month:'2026-99'}),/month/);
assert.throws(()=>validateState({...state,rows:[{...row,id:'<script>'}]}),/id/);
assert.throws(()=>validateState({...state,rows:[{...row,status:'installed-and-paid'}]}),/status/);
assert.throws(()=>validateState({...state,password:'secret'}),/Unexpected/);
const catalog = [{id:'honeygain',mode:'passive'},{id:'testing-work',mode:'active'}];
const totals = summarize({...state,rows:[row,{...row,id:'testing-work',earnedUsd:70,cashInr:1000}]},catalog);
assert.ok(totals.active > totals.passive);
assert.equal(totals.cash,1000);
assert.equal(totals.actualCosts,100);
assert.equal(totals.netCash,900);
assert.equal(summarize({...state,rows:[{...row,status:'paused'}]},catalog).passive,0);
assert.equal(summarize({...state,rows:[{...row,included:false}]},catalog).passive,0);
assert.equal(summarize({...state,rows:[{...row,basis:'scenario',scenarioUsd:50}]},catalog).passive,0);
assert.ok(summarize({...state,rows:[{...row,basis:'scenario',scenarioUsd:50}]},catalog).scenarioPassive>0);
let workload = workloadForGap({...state,target:30000,activeHourlyNetInr:500,weeklyHoursAvailable:20},{passive:0,active:0});
assert.equal(workload.monthlyHours,60);
assert.equal(workload.weeklyHours,60/4.33);
assert.equal(workload.withinAvailability,true);
workload=workloadForGap({...state,target:30000,activeHourlyNetInr:300,weeklyHoursAvailable:5},{passive:0,active:0});
assert.equal(workload.monthlyHours,100);
assert.equal(workload.withinAvailability,false);
assert.equal(workloadForGap({...state,activeHourlyNetInr:null},totals).monthlyHours,null);
assert.equal(workloadForGap({...state,target:500}, {passive:0,active:600}).monthlyHours,0);
const old=validateState({version:1,fx:85,target:30000,month:'2026-11',rows:[row]});
assert.equal(old.version,3);assert.equal(old.weeklyHoursAvailable,null);assert.equal(old.rows[0].included,true);assert.equal(old.rows[0].payoutKind,'unconfirmed');assert.equal(old.rows[0].earnedUsd,7);assert.equal(old.rows[0].balanceUsd,3);
const unselected=validateState({version:1,fx:85,target:30000,month:'2026-11',rows:[{...row,included:false}]});
assert.equal(unselected.rows[0].included,false);
const prior=validateState({version:2,fx:85,target:30000,month:'2026-11',activeHourlyNetInr:500,weeklyHoursAvailable:20,rows:[row]});
assert.equal(prior.version,3);assert.equal(prior.activeHourlyNetInr,500);assert.equal(prior.rows[0].payoutKind,'unconfirmed');assert.equal(summarize(prior,catalog).passive,0);
assert.throws(()=>validateState({...state,activeHourlyNetInr:0}),/hourly/);
assert.throws(()=>validateState({...state,weeklyHoursAvailable:169}),/weekly/);
assert.throws(()=>validateState({version:1,fx:85,target:30000,month:'2026-11',rows:[{...row,included:'yes'}]}),/selection/);
assert.ok(Math.abs(workloadForGap({...state,activeHourlyNetInr:500},{passive:2000,active:3000}).monthlyHours-50)<1e-8);
const voucherRow={...row,id:'testing-work',payoutKind:'noncash',earnedUsd:100,days:30,costInr:0,feeUsd:0,loss:0};
const voucherTotals=summarize({...state,rows:[voucherRow]},catalog);
assert.equal(voucherTotals.active,0,'Voucher value must not count toward the cash target');
assert.equal(workloadForGap({...state,activeHourlyNetInr:500},voucherTotals).monthlyHours,60);
assert.equal(estimateRow({...voucherRow,payoutKind:'unconfirmed'},85).net,null,'Unconfirmed payout cannot create a cash estimate');
assert.equal(summarize({...state,rows:[{...voucherRow,basis:'scenario',scenarioUsd:100}]},catalog).scenarioActive,0);
assert.equal(summarize({...state,rows:[{...voucherRow,cashInr:250,actualCostInr:50}]},catalog).netCash,200,'Actual cash remains independent of forecast classification');
assert.throws(()=>validateState({...state,rows:[{...row,payoutKind:'voucher-as-cash'}]}),/payout/);
console.log('PASS: observation estimates, missing/zero income, threshold timing, scenario separation, pooled rows and strict import validation.');
